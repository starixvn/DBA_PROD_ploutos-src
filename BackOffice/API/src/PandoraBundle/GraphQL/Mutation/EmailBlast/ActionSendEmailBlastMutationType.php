namespace PandoraBundle\GraphQL\Mutation\EmailBlast;

use Youshido\GraphQLBundle\Field\AbstractContainerAwareField;
use Youshido\GraphQL\Config\Field\FieldConfig;
use Youshido\GraphQL\Execution\ResolveInfo;
use PandoraBundle\GraphQL\Config\ApiTypes\ApiResponseType;
use PandoraBundle\Service\PandoraBackendService;
use Youshido\GraphQL\Type\NonNullType;
use Youshido\GraphQL\Type\Scalar\IdType;

class ActionSendEmailBlastMutationType extends AbstractContainerAwareField
{
    public function getDescription(){
        return 'Action Send Email Blast';
    }

    public function build(FieldConfig $config)
    {
        $this->addArguments([
            'Id' => new NonNullType(new IdType())
        ]);
    }
    
    public function getType()
    {
        return new ApiResponseType();
    }
    
    public function resolve($value, array $args, ResolveInfo $info)
    {
        $pandoraApi = $this->container->get(PandoraBackendService::class);
        $pandoraApi->setParameters('EmailBlast/SendEmail', 'POST', [
            'Id' => $args['Id']
        ]);
        return ['apiResult' => json_encode($pandoraApi->executeQuery($info))];
    }
}